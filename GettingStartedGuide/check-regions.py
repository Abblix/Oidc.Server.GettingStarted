"""Checks that the documentation site can show every line of the files the guide writes.

The guide takes its code from these files by region, or a file whole. A line outside every region of
a file the guide never shows whole is a line the reader is never told to write, so guide.sh builds
something the guide does not describe. Such a line is allowed only when `dotnet new mvc` generates it
in the same file, since the reader has it already.

Region markers, the same rule the site's include follows: a line that, stripped of its indentation,
is `// #region <name>`, `# #region <name>` or `@* #region <name> *@` opens a region, and
`// #endregion`, `# #endregion` or `@* #endregion *@` closes the innermost open one.

Usage: python check-regions.py   (needs the .NET SDK the guide uses)
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# Files the guide shows whole, so each of their lines is shown
WHOLE_FILES = {
    "OpenIDProviderApp/Program.cs",
    "OpenIDProviderApp/appsettings.json",
    "OpenIDProviderApp/TestUserStorage.cs",
    "OpenIDProviderApp/Controllers/AuthController.cs",
    "OpenIDProviderApp/Views/Auth/Login.cshtml",
    "TestClientApp/appsettings.json",
    "TestClientApp/appsettings.Development.json",
    "TestClientApp/Controllers/HomeController.cs",
    "TestClientApp/Views/Home/Index.cshtml",
}

# Not files the guide writes: the script that follows the guide, and this check
NOT_GUIDE_FILES = {"guide.sh", "check-regions.py"}

PROJECTS = ("OpenIDProviderApp", "TestClientApp")

OPENERS = (("// #region ", ""), ("# #region ", ""), ("@* #region ", " *@"))
CLOSERS = ("// #endregion", "# #endregion", "@* #endregion *@")


def read_lines(path):
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").split("\n")


def region_opened(stripped):
    for prefix, suffix in OPENERS:
        if stripped.startswith(prefix) and stripped.endswith(suffix):
            name = stripped[len(prefix):len(stripped) - len(suffix)].strip()
            if name:
                return name
    return None


def outside_regions(path, problems):
    """Yields (line number, line) of every line outside all regions; reports broken markers."""
    open_regions = []
    names = set()
    for number, line in enumerate(read_lines(path), start=1):
        stripped = line.strip()
        name = region_opened(stripped)
        if name is not None:
            if name in names:
                problems.append(f"{path.relative_to(ROOT).as_posix()}:{number}: region '{name}' is opened twice")
            names.add(name)
            open_regions.append(name)
        elif stripped in CLOSERS:
            if not open_regions:
                problems.append(f"{path.relative_to(ROOT).as_posix()}:{number}: #endregion closes no region")
            else:
                open_regions.pop()
        elif not open_regions:
            yield number, line
    for name in open_regions:
        problems.append(f"{path.relative_to(ROOT).as_posix()}: region '{name}' is never closed")


def generate_templates(target):
    for project in PROJECTS:
        subprocess.run(
            ["dotnet", "new", "mvc", "-n", project, "-o", str(target / project)],
            check=True, stdout=subprocess.DEVNULL)


def main():
    problems = []
    files = sorted(
        path for path in ROOT.rglob("*")
        if path.is_file() and path.relative_to(ROOT).as_posix() not in NOT_GUIDE_FILES)
    relative = {path.relative_to(ROOT).as_posix() for path in files}
    for missing in sorted(WHOLE_FILES - relative):
        problems.append(f"{missing}: listed as shown whole, but there is no such file")

    with tempfile.TemporaryDirectory() as temp:
        templates = Path(temp)
        generate_templates(templates)
        for path in files:
            name = path.relative_to(ROOT).as_posix()
            outside = list(outside_regions(path, problems))
            if name in WHOLE_FILES:
                continue
            template = templates / name
            template_lines = set(read_lines(template)) if template.is_file() else set()
            for number, line in outside:
                if line not in template_lines:
                    problems.append(
                        f"{name}:{number}: outside every region and not generated by dotnet new mvc: {line.strip()}")

    for problem in problems:
        print(f"check-regions: {problem}", file=sys.stderr)
    if problems:
        sys.exit(1)
    print(f"check-regions: every line of {len(files)} files is in a region, a file shown whole, "
          "or the dotnet new mvc template")


main()
